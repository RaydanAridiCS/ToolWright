#!/usr/bin/env node
/**
 * Generates docs/tools.md, a catalogue of every tool, from the tools' meta.ts files.
 * Run with `npm run docs:tools`. CI fails if the committed file is out of date (`--check`).
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const toolsDir = join(root, "packages/tools/src/tools");
const out = join(root, "docs/tools.md");

const field = (source, key) => {
  const m = new RegExp(`${key}:\\s*"((?:[^"\\\\]|\\\\.)*)"`).exec(source) ?? new RegExp(`${key}:\\s*\\n\\s*"((?:[^"\\\\]|\\\\.)*)"`).exec(source);
  return m ? m[1].replace(/\\"/g, '"').replace(/\\\\/g, "\\") : "";
};

const categoriesSource = readFileSync(join(root, "packages/tools/src/categories.ts"), "utf8");
const categories = [...categoriesSource.matchAll(/\{ id: "([a-z]+)", name: "([^"]+)", description: "([^"]+)"/g)].map((m) => ({ id: m[1], name: m[2], description: m[3] }));

const tools = readdirSync(toolsDir)
  .filter((d) => existsSync(join(toolsDir, d, "meta.ts")))
  .sort()
  .map((slug) => {
    const source = readFileSync(join(toolsDir, slug, "meta.ts"), "utf8");
    return { slug, name: field(source, "name"), tagline: field(source, "tagline"), category: field(source, "category"), popular: /popular:\s*true/.test(source) };
  });

const lines = [
  "# Tool catalogue",
  "",
  `Toolwright currently ships **${tools.length} tools**. Every one runs entirely in your browser.`,
  "",
  "> This file is generated by `npm run docs:tools` from each tool's `meta.ts`. Do not edit it by hand.",
  "",
];
for (const c of categories) {
  const list = tools.filter((t) => t.category === c.id);
  if (!list.length) continue;
  lines.push(`## ${c.name} (${list.length})`, "", c.description, "", "| Tool | What it does |", "| --- | --- |");
  for (const t of list) lines.push(`| [${t.name}](../packages/tools/src/tools/${t.slug}) ${t.popular ? "⭐" : ""} | ${t.tagline} |`);
  lines.push("");
}
const content = lines.join("\n").replace(/ +\|/g, " |");

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== content) {
    console.error("docs/tools.md is out of date. Run `npm run docs:tools`.");
    process.exit(1);
  }
} else {
  writeFileSync(out, content);
  console.log(`docs/tools.md: ${tools.length} tools`);
}
